export function skinUv(x: number, y: number) {
  const angle = (Math.atan2(y - BODY_CENTER_Y, x) + Math.PI * 2) % (Math.PI * 2)
  const index = (angle / (Math.PI * 2)) * contour.length
  const base = Math.floor(index)
  const fraction = index - base
  const radius = contour[base] * (1 - fraction) + contour[(base + 1) % contour.length] * fraction
  // Keep the final sample just inside the alpha edge to avoid premultiplied fringes.
  const reach = radius * Math.min(0.986, silhouetteFraction(x, y))
  return {
    u: (654.5 + Math.cos(angle) * reach * (1119 / 3.2)) / 1254,
    v: 1 - (1088 - BODY_CENTER_Y * (916 / 2.735) - Math.sin(angle) * reach * (916 / 2.735)) / 1254,
  }
}
